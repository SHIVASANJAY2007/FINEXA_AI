export function getLangCode(langStr) {
  if (!langStr) return 'en';
  const l = String(langStr).toLowerCase();
  if (l.includes('hindi') || l.includes('हिन्दी')) return 'hi';
  if (l.includes('tamil') || l.includes('தமிழ்')) return 'ta';
  if (l.includes('marathi') || l.includes('मराठी')) return 'mr';
  if (l.includes('bengali') || l.includes('বাংলা')) return 'bn';
  if (l.includes('telugu') || l.includes('తెలుగు')) return 'te';
  if (l.includes('kannada') || l.includes('ಕನ್ನಡ')) return 'kn';
  if (l.includes('malayalam') || l.includes('മലയാളം')) return 'ml';
  if (l.includes('gujarati') || l.includes('ગુજરાતી')) return 'gu';
  if (l.includes('odia') || l.includes('ଓଡ଼ିଆ')) return 'or';
  if (l.includes('punjabi') || l.includes('ਪੰਜਾਬੀ')) return 'pa';
  if (l.includes('assamese') || l.includes('অসমীয়া')) return 'as';
  return 'en';
}

